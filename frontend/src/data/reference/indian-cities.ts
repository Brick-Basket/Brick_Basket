/** Case-insensitive "starts with, then contains" match, capped for a usable dropdown. */
export function searchIndianCities(query: string, limit = 8): IndianCity[] {
  const q = query.trim().toLowerCase();
  if (q.length < 2) return [];
  const starts = INDIAN_CITIES.filter((c) => c.city.toLowerCase().startsWith(q));
  const contains = INDIAN_CITIES.filter(
    (c) => !c.city.toLowerCase().startsWith(q) && c.city.toLowerCase().includes(q),
  );
  return [...starts, ...contains].slice(0, limit);
}
